--
-- 2026-10-28 ユーザー指定: 送信済みは受信箱(アドレス)ごとに見る。受信箱のタブ「送信済み」で、
-- そのアドレスから送ったメール(差出人 = 受信箱のアドレス)を新しい順に出すための索引。
-- 送信メールの差出人は全件小文字で入っている(2026-10-28 に確認)ので、そのままの値で引く。表の列は変えない。
--
-- ※ CONCURRENTLY はトランザクションの中では実行できないため、SQL Editor では 1 文で実行する。
-- ============================================================================

CREATE INDEX CONCURRENTLY IF NOT EXISTS idx_mail_messages_out_from_sent
  ON public.mail_messages (from_address, sent_at DESC, id DESC)
  WHERE direction = 'out';
