-- ============================================================================
-- migration 74: 会員に「都道府県」を追加 (2026-08)
--
-- 背景:
--   会員情報CSV には独立した都道府県列がなく、住所は「住所(フル）」1列のみ
--   (例: 東京都多摩市桜ヶ丘1-50-7)。レポートで都道府県別に集計・絞り込みしたい
--   (CLAUDE.md §5.4)。
--
-- 対応:
--   - members.address の先頭にある47都道府県名を抜き出す**生成カラム**を追加する。
--     通常カラム + 取込時に書き込む方式ではなく生成カラムにした理由:
--       * 取込経路が2つある (画面/定期取込 = lib/import/members_map.ts、
--         初期一括移行 = scripts/import/02_members.ts)。どちらも address を
--         個別に書いており、都道府県の導出を両方に持たせるとズレる余地が残る。
--       * 生成カラムなら導出式がDBに1つだけになり、既存データも本migration適用時に
--         自動で埋まる (バックフィルUPDATE不要)。住所を編集すれば自動追従する。
--     代償として個別レコードの手修正はできない (住所を直して直す)。
--
-- 実データでの検証 (csv/会員情報.csv, 住所あり 23,533件):
--   - 都道府県を抽出できた: 22,912件 (97.4%)
--   - NULL となった 621件は**すべて海外住所** (「ドイツObere Hausbreite 13 ...」等、
--     国名プレフィックス)。国内住所の取りこぼしは 0 件。
--   - 47県名に前方一致の重複はない (ある県名が別の県名の接頭辞にならない) ため、
--     選択肢の並び順に依存せず一意に定まる。
--
-- 表示:
--   - レポートのみ (lib/reports/schema_all.ts の MEMBER_COLUMNS に追加)。
--   - 会員一覧/詳細には出さないため field_definitions には登録しない。
-- ============================================================================

ALTER TABLE public.members
  ADD COLUMN IF NOT EXISTS prefecture text
  GENERATED ALWAYS AS (
    substring(
      address
      from '^[[:space:]　]*(北海道|青森県|岩手県|宮城県|秋田県|山形県|福島県|茨城県|栃木県|群馬県|埼玉県|千葉県|東京都|神奈川県|新潟県|富山県|石川県|福井県|山梨県|長野県|岐阜県|静岡県|愛知県|三重県|滋賀県|京都府|大阪府|兵庫県|奈良県|和歌山県|鳥取県|島根県|岡山県|広島県|山口県|徳島県|香川県|愛媛県|高知県|福岡県|佐賀県|長崎県|熊本県|大分県|宮崎県|鹿児島県|沖縄県)'
    )
  ) STORED;

COMMENT ON COLUMN public.members.prefecture IS
  '都道府県 (address 先頭の47都道府県名から自動導出する生成カラム。海外住所は NULL。手修正不可)';

-- レポートでの都道府県別グルーピング/絞り込み用。
CREATE INDEX IF NOT EXISTS idx_members_prefecture
  ON public.members(prefecture)
  WHERE deleted_at IS NULL;
